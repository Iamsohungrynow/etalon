"""Write studio/src/field/colormaps.ts: 256-entry RGB tables of the field colormaps.

ui-ux-spec §7: viridis for magnitudes, RdBu for signed values, "both from matplotlib
definitions". The tables are sampled from matplotlib once, here, and committed; the
frontend has no matplotlib (or any colormap library) at run time.

    viridis   matplotlib's ``viridis`` (a 256-entry ListedColormap), taken as is.
    RdBu      matplotlib's ``RdBu_r``: index 0 is blue (most negative), index 255 red
              (most positive), the white-ish centre at 128 = 0.5 * 256. Exposed as
              ``RdBu`` because that is the name the spec and the UI use.

Each channel is round(255 * c), so viridis[0] = (68, 1, 84) and viridis[255] =
(253, 231, 37), the values matplotlib documents.

Run from the repository root (matplotlib is in the repo venv):

    .venv\\Scripts\\python.exe studio\\scripts\\gen_colormaps.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib
import numpy as np
from matplotlib import colormaps

N = 256
TRIPLES_PER_LINE = 8
OUT = Path(__file__).resolve().parent.parent / "src" / "field" / "colormaps.ts"

# (name exported in TypeScript, matplotlib colormap name)
TABLES = [("viridis", "viridis"), ("RdBu", "RdBu_r")]


def rgb_table(mpl_name: str) -> np.ndarray:
    """The colormap's N lookup-table entries as an (N, 3) uint8 array."""
    cmap = colormaps[mpl_name].resampled(N)
    rgba = cmap(np.arange(N))  # integer input indexes the LUT directly
    return np.rint(rgba[:, :3] * 255.0).astype(np.uint8)


def ts_array(name: str, mpl_name: str, rgb: np.ndarray) -> str:
    lines = []
    for start in range(0, N, TRIPLES_PER_LINE):
        row = rgb[start : start + TRIPLES_PER_LINE]
        lines.append("  " + " ".join(f"{r}, {g}, {b}," for r, g, b in row))
    body = "\n".join(lines)
    return (
        f"/** matplotlib `{mpl_name}`: {N} RGB triples, flat (r0, g0, b0, r1, …). */\n"
        f"export const {name}: Uint8Array = new Uint8Array([\n{body}\n]);\n"
    )


def main() -> None:
    header = f"""\
/*
 * GENERATED by studio/scripts/gen_colormaps.py from matplotlib {matplotlib.__version__}.
 * Do not edit by hand; rerun the script instead.
 *
 * Field colormaps (ui-ux-spec §7), {N} entries each, every channel round(255 * c):
 *
 * - viridis: by Stéfan van der Walt and Nathaniel J. Smith (with Eric Firing),
 *   released under CC0 1.0 (public-domain dedication). Perceptually uniform and
 *   colour-blind safe; for magnitudes.
 * - RdBu: from ColorBrewer, Copyright (c) 2002 Cynthia Brewer, Mark Harrower and
 *   The Pennsylvania State University, licensed under the Apache License 2.0
 *   (https://colorbrewer2.org/). This is matplotlib's RdBu_r: index 0 is blue
 *   (negative), index 255 red (positive), the centre (0.5) at index 128. For signed
 *   values with a symmetric range.
 *
 * The tables are data, not code: they are read only through src/field/render.ts.
 */

export type ColormapName = {" | ".join(f'"{name}"' for name, _ in TABLES)};

/** Entries per table; a table holds 3 * COLORMAP_SIZE bytes. */
export const COLORMAP_SIZE = {N};
"""
    parts = [header]
    for name, mpl_name in TABLES:
        parts.append(ts_array(name, mpl_name, rgb_table(mpl_name)))
    names = ", ".join(f"{name}" for name, _ in TABLES)
    parts.append(f"export const COLORMAPS: Record<ColormapName, Uint8Array> = {{ {names} }};\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({', '.join(name for name, _ in TABLES)})")


if __name__ == "__main__":
    main()
